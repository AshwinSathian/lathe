// Writes the parts of the docs that must match the code: the tool list and the licence notices.
// `--check` fails instead of writing, so CI catches docs that have drifted.
import { readFileSync, writeFileSync } from "node:fs";
import { GROUPS, tools } from "../src/data/tools.ts";

const check = process.argv.includes("--check");
const stale = [];
const put = (file, text) => {
  let now = ""; try { now = readFileSync(file, "utf8"); } catch { /* New file. */ }
  if (now === text) return;
  if (check) stale.push(file); else writeFileSync(file, text);
};

const base = tools.filter((t) => !t.run), presets = tools.filter((t) => t.run);
const rows = (kind) => GROUPS[kind].map((g) => `| ${g} | ${base.filter((t) => t.kind === kind && t.group === g).map((t) => `[${t.name}](https://lathe.ashwinsathian.com/${t.id})`).join(", ")} |`).join("\n");
const summary = `<!-- tools:start (generated by npm run docs) -->
**${tools.length} tool pages:** ${base.length} tools and ${presets.length} one-click format conversions such as [HEIC to JPG](https://lathe.ashwinsathian.com/heic-to-jpg).

| Images | |
|---|---|
${rows("image")}

| PDF | |
|---|---|
${rows("pdf")}
<!-- tools:end -->`;
put("README.md", readFileSync("README.md", "utf8").replace(/<!-- tools:start[\s\S]*?<!-- tools:end -->/, summary));

const detail = (kind) => GROUPS[kind].map((g) => `### ${g}\n\n| Tool | What it does | Runs on |\n|---|---|---|\n${tools.filter((t) => t.kind === kind && t.group === g).map((t) => `| [${t.name}](https://lathe.ashwinsathian.com/${t.id}) | ${t.blurb} | ${t.tech} |`).join("\n")}`).join("\n\n");
put("docs/tools.md", `# Every tool\n\nGenerated from [\`src/data/tools.ts\`](../src/data/tools.ts) by \`npm run docs\`.\n\n## Images\n\n${detail("image")}\n\n## PDF\n\n${detail("pdf")}\n`);

// Licences of everything that ships to the browser.
const direct = Object.keys(JSON.parse(readFileSync("package.json", "utf8")).dependencies).filter((n) => n !== "astro" && n !== "@astrojs/sitemap");
const list = direct.map((n) => { const m = JSON.parse(readFileSync(`node_modules/${n}/package.json`, "utf8")); return { name: n, version: m.version, license: m.license ?? "see package", url: `https://www.npmjs.com/package/${n}` }; }).sort((a, b) => a.name.localeCompare(b.name));
const extra = [
  ["libheif, libde265 (inside libheif-js)", "LGPL-3.0", "https://github.com/strukturag/libheif"],
  ["qpdf (inside qpdf-wasm)", "Apache-2.0", "https://github.com/qpdf/qpdf"],
  ["ONNX Runtime Web", "MIT", "https://github.com/microsoft/onnxruntime"],
  ["BiRefNet Lite, WebGPU build (model)", "MIT", "https://huggingface.co/jiabins0303/birefnet-lite-1024-webgpu"],
  ["MODNet, ONNX conversion (model)", "Apache-2.0", "https://huggingface.co/Xenova/modnet"],
  ["Swin2SR x2 (model)", "Apache-2.0", "https://huggingface.co/Xenova/swin2SR-classical-sr-x2-64"],
  ["BlazeFace short range (model)", "Apache-2.0", "https://ai.google.dev/edge/mediapipe/solutions/vision/face_detector"],
  ["Tesseract language data", "Apache-2.0", "https://github.com/naptha/tessdata"],
  ["Bricolage Grotesque (font)", "OFL-1.1", "https://github.com/ateliertriay/bricolage"],
];
put("THIRD_PARTY_NOTICES.md", `# Third-party notices\n\nLathe's own code is MIT licensed. It ships or downloads the components below, each under its own licence. Generated by \`npm run docs\`.\n\nlibheif is LGPL-3.0. Lathe loads it as a separate, unmodified JavaScript and WebAssembly module, so you can replace it by swapping the \`libheif-js\` dependency and rebuilding.\n\n| Package | Version | Licence |\n|---|---|---|\n${list.map((x) => `| [${x.name}](${x.url}) | ${x.version} | ${x.license} |`).join("\n")}\n\n| Bundled engine, model or font | Licence |\n|---|---|\n${extra.map(([n, l, u]) => `| [${n}](${u}) | ${l} |`).join("\n")}\n`);
put("public/licenses.txt", `Lathe is MIT licensed: https://github.com/AshwinSathian/lathe\n\nIt uses these open-source components.\n\n${[...list.map((x) => `${x.name} ${x.version}: ${x.license}. ${x.url}`), ...extra.map(([n, l, u]) => `${n}: ${l}. ${u}`)].join("\n")}\n`);

if (stale.length) { console.error(`Out of date: ${stale.join(", ")}. Run npm run docs.`); process.exit(1); }
